/*
 1. Top Selling Products
 Query the top 10 products by total sales value.
 Challenge: Include product name, total quantity sold, and total sales value.
 */
 
 -- using group by & limit
 select
	p.product_id,
	p.product_name,
    sum(oi.total_price) as total_sales,
    count(o.order_id) as total_orders
 from orders o
 join order_items oi
 on o.order_id = oi.order_id
 join products p
 on oi.product_id = p.product_id
 group by p.product_id, p.product_name
 order by total_sales desc
 limit 10
 ;
 
 /*
2. Revenue by Category
Calculate total revenue generated by each product category.
Challenge: Include the percentage contribution of each category to total revenue.
*/
with total_revenue_by_category as (
select 
	c.category_id, 
    c.category_name,
    sum(oi.total_price)/(select sum(total_price) from order_items)*100 as percent_contribution
from order_items oi
join products p
on oi.product_id = p.product_id
join category c 
on p.category_id = c.category_id
group by c.category_id, c.category_name)

select 
	*
from total_revenue_by_category;

/*
3. Average Order Value (AOV)
Compute the average order value for each customer.
Challenge: Include only customers with more than 5 orders.
*/

-- customer total orders revenue / customer total orders = AOV

select
	c.customer_id,
    concat(c.first_name,' ',c.last_name) as full_name,
    count(c.customer_id) as order_count,
    sum(oi.total_price)/count(o.customer_id) as avg_order_value
from orders o
join order_items oi
on o.order_id = oi.order_id
join customers c
on o.customer_id = c.customer_id
group by c.customer_id
having count(c.customer_id) > 5
;


/*
4. Monthly Sales Trend
Query monthly total sales over the past year.
Challenge: Display the sales trend, grouping by month, return current_month sale, last month sale!
*/
with monthly_sales_trend as (
select
	year(o.order_date) as sale_year, month(o.order_date) as sale_month,
	sum(oi.total_price) as total_sales
from orders o
join order_items oi
on o.order_id = oi.order_id
where order_date >= current_date() - interval 1 year
group by year(o.order_date), month(o.order_date) 
order by year(o.order_date) asc, month(o.order_date) asc
)

select
	sale_year,
    sale_month,
    total_sales,
    lag(total_sales, 1) over(order by sale_year, sale_month ) as last_month_sale
from monthly_sales_trend;

