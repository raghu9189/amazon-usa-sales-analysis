/*
6. Least-Selling Categories by State
Identify the least-selling product category for each state.
Challenge: Include the total sales for that category within each state.
*/
with ranked_sales as (
select 
	c.state,
    cg.category_name,
    sum(oi.total_price) as total_sales,
    rank() over(partition by c.state order by sum(oi.total_price)) as lowest_rank
from orders as o
join customers as c
on o.customer_id = c.customer_id
join order_items as oi
on o.order_id = oi.order_id
join products as p 
on oi.product_id = p.product_id
join category as cg 
on p.category_id = cg.category_id
group by c.state, cg.category_id )
select 
	*
from ranked_sales
where lowest_rank = 1
;

/*
7. Customer Lifetime Value (CLTV)
Calculate the total value of orders placed by each customer over their lifetime.
Challenge: Rank customers based on their CLTV.
*/

select 
	concat(c.first_name, ' ', c.last_name) as full_name,
    sum(oi.total_price) as cltv,
    dense_rank() over(order by sum(oi.total_price) desc) as ranked
from orders as o
join customers as c
on o.customer_id = c.customer_id
join order_items as oi
on o.order_id = oi.order_id
group by c.customer_id;

/*
8. Inventory Stock Alerts
Query products with stock levels below a certain threshold (e.g., less than 10 units).
Challenge: Include last restock date and warehouse information.
*/
select 
	p.product_name,
	i.inventory_id,
    i.stock,
    i.warehouse_id,
    i.last_stock_date
from products p
join inventory i
on p.product_id = i.product_id
where stock < 10
;


/*
9. Shipping Delays
Identify orders where the shipping date is later than 3 days after the order date.
Challenge: Include customer, order details, and delivery provider.
*/
select 
	o.order_id,
	o.order_date,
    s.shipping_date,
    datediff(s.shipping_date, o.order_date) as difference_date,
    concat(c.first_name, ' ', c.last_name) as full_name,
    s.shipping_providers
from orders o
join shipping s
on o.order_id = s.order_id
join customers c 
on c.customer_id = o.customer_id
where s.shipping_date > o.order_date + interval 3 day
;


/*
10. Payment Success Rate 
Calculate the percentage of successful payments across all orders.
Challenge: Include breakdowns by payment status (e.g., failed, pending).
*/

select
	p.payment_status,
    count(p.payment_status) as payment_count,
    round(count(p.payment_status)/( select count(payment_status) from payments) * 100,2)  as payment_rate
from orders o
join payments p
on o.order_id = p.order_id
group by p.payment_status
;

/*
11. Top Performing Sellers
Find the top 5 sellers based on total sales value.
Challenge: Include both successful and failed orders, and display their percentage of successful orders.
*/
with top_sellers as (
select
	s.seller_id,
    s.seller_name,
    sum(oi.total_price) as total_sale
from orders o
join order_items oi
on o.order_id = oi.order_id
join sellers s 
on o.seller_id = s.seller_id
group by s.seller_id
order by total_sale desc
limit 5)
,
sellers_status
as (select
	o.seller_id,
	o.order_status,
    ts.total_sale,
	count(o.order_status) as status_counts
from orders o
join top_sellers ts
on o.seller_id = ts.seller_id
group by o.seller_id, o.order_status)

select * from 
sellers_status;

/*
12. Product Profit Margin
Calculate the profit margin for each product (difference between price and cost of goods sold).
Challenge: Rank products by their profit margin, showing highest to lowest.
*/
with top_products_by_margin as (
select 
	p.product_id,
    p.product_name,
    sum((p.price * oi.quantity) - (p.cogs * oi.quantity)) as total_profit,
    sum((p.price * oi.quantity) - (p.cogs * oi.quantity))/sum(p.price * oi.quantity)* 100  as profit_margin
from order_items oi
join products p
on oi.product_id = p.product_id
group by p.product_id )

select 
	product_name,
    total_profit,
    profit_margin,
    dense_rank() over(order by profit_margin desc) as 'rank'
from top_products_by_margin
;

