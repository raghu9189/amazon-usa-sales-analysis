/*
12. Product Profit Margin
Calculate the profit margin for each product (difference between price and cost of goods sold).
Challenge: Rank products by their profit margin, showing highest to lowest.
*/
with top_products_by_margin as (
select 
	p.product_id,
    p.product_name,
    sum((p.price * oi.quantity) - (p.cogs * oi.quantity)) as total_profit,
    sum((p.price * oi.quantity) - (p.cogs * oi.quantity))/sum(p.price * oi.quantity)* 100  as profit_margin
from order_items oi
join products p
on oi.product_id = p.product_id
group by p.product_id )

select 
	product_name,
    total_profit,
    profit_margin,
    dense_rank() over(order by profit_margin desc) as 'rank'
from top_products_by_margin
;

/*
13. Most Returned Products
Query the top 10 products by the number of returns.
Challenge: Display the return rate as a percentage of total units sold for each product.
*/
with products_with_returns as (
select
	p.product_id,
    p.product_name,
    count(p.product_id) as total_orders,
    sum(case when o.order_status = 'Returned' then 1 else 0 end) as return_count
from orders o
join order_items oi
on o.order_id = oi.order_id
join products p
on oi.product_id = p.product_id
group by p.product_id, p.product_name)

select
	product_id,
    product_name,
    return_count,
    (return_count/total_orders)*100 as return_percentage
from products_with_returns 
order by return_percentage desc
limit 10
;

/*
15. Inactive Sellers
Identify sellers who haven’t made any sales in the last 6 months.
Challenge: Show the last sale date and total sales from those sellers.
*/
with sellers_inactive as (
select
	*
from sellers 
where seller_id not in (
	select 
		seller_id 
	from orders 
    where order_date >= (current_date() - interval 6 month)
)
)
select
	o.seller_id,
    max(o.order_date) as last_order_date,
    max(oi.total_price) as last_total_sales
from orders o
join order_items oi
on o.order_id = oi.order_id
join sellers_inactive si
on o.seller_id = si.seller_id
group by o.seller_id
;

